/// Name of the register at or just below `off` (e.g. "SCCE1+2").
pub fn immr_name(off: u32) -> String {
    match IMMR_NAMES.iter().rev().find(|(o, _)| *o <= off) {
        Some((o, n)) if off == *o => n.to_string(),
        Some((o, n)) if off - o < 0x40 => format!("{n}+{:#x}", off - o),
        _ => format!("{off:#06x}"),
    }
}
